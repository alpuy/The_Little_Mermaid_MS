#!/usr/bin/env python3
"""Free areas of the NES fixed bank image (ROM page 0 of the SMS cartridge): bytes that are
only ever executed as 6502 code (the code runs translated from other pages), never read as
data. Output: an include with HOLE_<n> / HOLE_<n>_END (Z80 addresses), largest first."""
import re, sys
rx = re.compile(r'^([C-]) ([D-]) (.) (.) (.) (.) 0x([0-9A-F]{6}) ([0-9A-F]{2}):([0-9A-F]{4}): (.{9})\s*(.*)$')
free = [False] * 0x4000
for l in open(sys.argv[1], encoding='utf-8'):
    m = rx.match(l.rstrip('\n'))
    if not m: continue
    a = int(m.group(9), 16) - 0xC000
    by = m.group(10).split()
    isins = re.match(r'^[A-Z]{3}\b', m.group(11)) is not None
    ok = isins and m.group(2) != 'D'
    for k in range(len(by)):
        free[a + k] = ok
runs = []
s = None
for i in range(0x4001):
    f = i < 0x4000 and free[i]
    if f and s is None: s = i
    if not f and s is not None:
        runs.append((s, i)); s = None
runs.sort(key=lambda r: r[0] - r[1])
with open(sys.argv[2], 'w') as f:
    f.write('; generated by tools/holes.py: free areas of ROM page 0 (fixed NES bank image)\n')
    for n, (a, b) in enumerate(runs[:24]):
        f.write(f'HOLE_{n} equ 0{a:04X}h\nHOLE_{n}_END equ 0{b:04X}h      ; {b - a} bytes\n')
print('total', sum(b - a for a, b in runs), 'largest', [(hex(a), b - a) for a, b in runs[:12]])
